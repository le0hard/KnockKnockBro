import SwiftUI

/// Отметка "уже подключился" рядом с названием встречи (v0.5.0) — зелёная
/// галочка. Одинаковая в попапе Menu Bar, главном окне и календаре.
///
/// Кнопка "Подключиться" у такой встречи остаётся (можно переподключиться),
/// но перестаёт быть главной (акцентной) — внимание уже не нужно.
struct JoinedBadge: View {
    var body: some View {
        Image(systemName: "checkmark.circle.fill")
            .foregroundStyle(.green)
            .help("Вы уже подключились к этой встрече сегодня")
            .accessibilityLabel("Уже подключились")
    }
}
